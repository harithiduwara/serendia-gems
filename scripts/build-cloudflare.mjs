#!/usr/bin/env node
/**
 * Builds serendiagems.com for Cloudflare (a Worker serving static assets).
 *
 *   npm run build:cloudflare        → ./out, ready for `wrangler deploy`
 *
 * This is the command Cloudflare's build runs. It differs from the GitHub Pages
 * build in three ways, all because the site is served from its own domain:
 *
 *   · no basePath — the site lives at the root, not under /serendia-gems
 *   · canonical URLs, sitemap and Open Graph tags name https://serendiagems.com
 *   · a `_headers` file restores the security headers (GitHub Pages could not)
 *
 * Two guards worth knowing about:
 *
 *   1. The unit tests run first. Cloudflare deploys on every push to main on its
 *      own, regardless of whether GitHub CI passed — so this build is the last
 *      gate before production, and a broken catalogue must fail it here.
 *
 *   2. src/app/api is moved aside for the build and put back afterwards, even if
 *      the build fails. The older Pages script deletes it outright, which is fine
 *      in a throwaway CI checkout but damaged the working tree when run locally.
 */
import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, renameSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const SITE_URL = 'https://serendiagems.com';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const apiDir = join(root, 'src', 'app', 'api');
// Inside node_modules so TypeScript, ESLint and git all ignore it.
const stash = join(root, 'node_modules', '.cache', 'serendia', 'api-stash');
const outDir = join(root, 'out');

const step = (msg) => console.log(`\n▸ ${msg}`);

const run = (cmd, args, env = {}) => {
  const result = spawnSync(cmd, args, {
    cwd: root,
    stdio: 'inherit',
    env: { ...process.env, ...env },
  });
  if (result.status !== 0) {
    throw new Error(`${cmd} ${args.join(' ')} exited with ${result.status ?? result.signal}`);
  }
};

/** Puts the API route back. Safe to call when there is nothing to restore. */
const restoreApi = () => {
  if (!existsSync(stash)) return;
  if (existsSync(apiDir)) {
    // Both exist: the tracked copy in src/ is authoritative.
    rmSync(stash, { recursive: true, force: true });
  } else {
    renameSync(stash, apiDir);
  }
};

let failed = false;

try {
  // A previous run killed mid-build could have left the route stashed.
  restoreApi();

  step('Unit tests — the last gate before production');
  run('npx', ['vitest', 'run']);

  step('Setting aside src/app/api (a static export cannot contain a POST route)');
  if (existsSync(apiDir)) {
    mkdirSync(dirname(stash), { recursive: true });
    renameSync(apiDir, stash);
  }

  step(`Static export for ${SITE_URL}`);
  rmSync(outDir, { recursive: true, force: true });
  run('npx', ['next', 'build'], {
    STATIC_EXPORT: '1',
    NEXT_PUBLIC_STATIC_EXPORT: '1',
    // Forced, not defaulted: a stray GitHub Pages value in the environment
    // would otherwise put every asset under /serendia-gems and break the site.
    NEXT_PUBLIC_BASE_PATH: '',
    NEXT_PUBLIC_SITE_URL: SITE_URL,
  });

  step('Writing out/_headers');
  const securityHeaders = JSON.parse(
    readFileSync(join(root, 'config', 'security-headers.json'), 'utf8'),
  );
  const lines = [
    '# Generated by scripts/build-cloudflare.mjs from config/security-headers.json.',
    '# Do not edit in out/ — it is rebuilt on every deploy.',
    '/*',
    ...securityHeaders.map(({ key, value }) => `  ${key}: ${value}`),
    '',
    // Next fingerprints everything under /_next/static, so a changed file always
    // gets a new URL and these can be cached for a year without going stale.
    '/_next/static/*',
    '  Cache-Control: public, max-age=31536000, immutable',
    '',
  ];
  writeFileSync(join(outDir, '_headers'), lines.join('\n'));

  step('Checking the output is deployable');
  const required = ['index.html', '404.html', '_headers', 'sitemap.xml', 'robots.txt', 'gem/HR16/index.html'];
  const missing = required.filter((f) => !existsSync(join(outDir, f)));
  if (missing.length) throw new Error(`out/ is missing: ${missing.join(', ')}`);

  const sitemap = readFileSync(join(outDir, 'sitemap.xml'), 'utf8');
  if (!sitemap.includes(`${SITE_URL}/gem/HR16`)) {
    throw new Error(`sitemap.xml does not use ${SITE_URL} — canonical URLs would be wrong`);
  }
  if (sitemap.includes('/serendia-gems/')) {
    throw new Error('sitemap.xml still contains the GitHub Pages basePath');
  }
  console.log(`  ✓ ${required.length} required files present, URLs point at ${SITE_URL}`);
} catch (err) {
  failed = true;
  console.error(`\n✗ Cloudflare build failed: ${err.message}`);
} finally {
  restoreApi();
}

if (failed) process.exit(1);
console.log('\n✓ Ready. Deploy with: npx wrangler deploy');
